-- On-demand snapshots. No automatic freshness claim.
USE DATABASE IDENTIFIER($DEMO_DB);
USE SCHEMA CURATED;
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT portfolio.ID AS ENTITY_ID, portfolio.NAME AS ENTITY_NAME,
       portfolio.REGION, portfolio.CATEGORY, portfolio.RISK_TIER, portfolio.STATUS,
       COUNT(*) AS EVENT_COUNT,
       SUM(observation.INSTALLMENT_COUNT) AS INSTALLMENT_COUNT,
       SUM(observation.VALUE_MYR) AS VALUE_MYR,
       SUM(observation.ARREARS_COUNT) AS ARREARS_COUNT,
       SUM(observation.ESCALATED_COUNT) AS ESCALATED_COUNT,
       SUM(observation.SLA_BREACHED) AS SLA_BREACH_COUNT,
       SUM(observation.REVIEW_DUE) AS REVIEW_DUE,
       SUM(observation.REVIEW_COMPLETED) AS REVIEW_COMPLETED,
       100.0 * (SUM(observation.INSTALLMENT_COUNT) - SUM(observation.ARREARS_COUNT)) / NULLIF(SUM(observation.INSTALLMENT_COUNT), 0) AS ON_TIME_RATE_PCT,
       100.0 * SUM(observation.ESCALATED_COUNT) / NULLIF(SUM(observation.ARREARS_COUNT), 0) AS ESCALATION_SHARE_PCT,
       100.0 * SUM(observation.REVIEW_COMPLETED) / NULLIF(SUM(observation.REVIEW_DUE), 0) AS REVIEW_COMPLIANCE_PCT,
       AVG(observation.AUTODEBIT_REJECT_PCT) AS AVG_AUTODEBIT_REJECT_PCT,
       MAX(observation.EVENT_DATE) AS SOURCE_WATERMARK
FROM RAW.PORTFOLIO_DAILY observation
JOIN RAW.PORTFOLIOS portfolio ON portfolio.ID = observation.ENTITY_ID
GROUP BY portfolio.ID, portfolio.NAME, portfolio.REGION, portfolio.CATEGORY, portfolio.RISK_TIER, portfolio.STATUS;

CREATE DYNAMIC TABLE CURATED.TREND_ANALYSIS
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT EVENT_DATE AS METRIC_DATE, COUNT(*) AS EVENT_COUNT,
       SUM(INSTALLMENT_COUNT) AS INSTALLMENT_COUNT, SUM(VALUE_MYR) AS VALUE_MYR,
       SUM(ARREARS_COUNT) AS ARREARS_COUNT, SUM(ESCALATED_COUNT) AS ESCALATED_COUNT,
       100.0 * SUM(ESCALATED_COUNT) / NULLIF(SUM(ARREARS_COUNT), 0) AS ESCALATION_SHARE_PCT
FROM RAW.PORTFOLIO_DAILY
GROUP BY EVENT_DATE;

CREATE DYNAMIC TABLE CURATED.ARREARS_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT ARREARS_REASON, SUM(ARREARS_COUNT) AS ARREARS_COUNT,
       SUM(ESCALATED_COUNT) AS ESCALATED_COUNT,
       SUM(SLA_BREACHED) AS SLA_BREACH_COUNT,
       SUM(VALUE_MYR) AS EXPOSED_VALUE_MYR,
       100.0 * SUM(ESCALATED_COUNT) / NULLIF(SUM(ARREARS_COUNT), 0) AS ESCALATION_SHARE_PCT
FROM RAW.PORTFOLIO_DAILY
WHERE ARREARS_COUNT > 0
GROUP BY ARREARS_REASON;

CREATE DYNAMIC TABLE CURATED.KPI_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
WITH observations AS (
  SELECT SUM(INSTALLMENT_COUNT) AS INSTALLMENTS, SUM(ARREARS_COUNT) AS ARREARS,
         SUM(ESCALATED_COUNT) AS ESCALATED, SUM(SLA_BREACHED) AS BREACHES, SUM(VALUE_MYR) AS VALUE_MYR,
         SUM(REVIEW_DUE) AS REVIEW_DUE, SUM(REVIEW_COMPLETED) AS REVIEW_COMPLETED,
         MAX(EVENT_DATE) AS SOURCE_WATERMARK
  FROM RAW.PORTFOLIO_DAILY
), book AS (SELECT COUNT(*) AS PORTFOLIO_COUNT FROM RAW.PORTFOLIOS),
documents AS (
  SELECT 100.0 * SUM(LEAST(ON_FILE_QTY, REQUIRED_QTY)) / NULLIF(SUM(REQUIRED_QTY), 0) AS COVERAGE_PCT,
         SUM(PENDING_QTY) AS PENDING
  FROM RAW.FINANCING_DOCUMENTS
), metrics AS (
  SELECT 1 AS SORT_ORDER, 'On-Time Collection Rate' AS TITLE,
         100.0 * (INSTALLMENTS - ARREARS) / NULLIF(INSTALLMENTS, 0) AS VALUE_NUM, '%' AS UNIT FROM observations
  UNION ALL SELECT 2, 'Arrears Cases', ARREARS, '' FROM observations
  UNION ALL SELECT 3, 'Escalated to Restructuring Review', ESCALATED, '' FROM observations
  UNION ALL SELECT 4, 'Escalation Rate', 100.0 * ESCALATED / NULLIF(ARREARS, 0), '%' FROM observations
  UNION ALL SELECT 5, 'Contact SLA Breaches', BREACHES, '' FROM observations
  UNION ALL SELECT 6, 'Scheduled Value (MYR M)', VALUE_MYR / 1e6, '' FROM observations
  UNION ALL SELECT 7, 'Installments Due', INSTALLMENTS, '' FROM observations
  UNION ALL SELECT 8, 'Account Review Compliance', 100.0 * REVIEW_COMPLETED / NULLIF(REVIEW_DUE, 0), '%' FROM observations
  UNION ALL SELECT 9, 'Portfolios Monitored', PORTFOLIO_COUNT, '' FROM book
  UNION ALL SELECT 10, 'Financing File Coverage', COVERAGE_PCT, '%' FROM documents
  UNION ALL SELECT 11, 'Financing Documents Pending', PENDING, '' FROM documents
)
SELECT metrics.SORT_ORDER, metrics.TITLE, metrics.VALUE_NUM,
       IFF(metrics.VALUE_NUM IS NULL, 'Unavailable',
           CASE WHEN metrics.UNIT = '' THEN TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM), '999,999,999,990'))
                WHEN metrics.SORT_ORDER = 1 THEN TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM, 2), '990.00'))
                ELSE TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM, 1), '990.0')) END || metrics.UNIT) AS DISPLAY,
       'neutral' AS STATUS, observations.SOURCE_WATERMARK
FROM metrics CROSS JOIN observations;

ALTER DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.TREND_ANALYSIS SUSPEND;
ALTER DYNAMIC TABLE CURATED.ARREARS_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.KPI_SUMMARY SUSPEND;
